export const formatBDT = (amount: number, lang: Language = 'en'): string => {
  const formatted = new Intl.NumberFormat('en-IN', {
    maximumFractionDigits: 0,
  }).format(Math.round(amount));

  if (lang === 'bn') {
    const bnDigits: Record<string, string> = {
      '0': '০',
      '1': '১',
      '2': '২',
      '3': '৩',
      '4': '৪',
      '5': '৫',
      '6': '৬',
      '7': '৭',
      '8': '৮',
      '9': '৯',
    };
    const bnStr = formatted.replace(/[0-9]/g, (d) => bnDigits[d] || d);
    return `৳ ${bnStr}`;
  }
  return `৳ ${formatted}`;
};

export const formatNum = (num: number, lang: Language = 'en'): string => {
  const str = num.toLocaleString('en-IN');
  if (lang === 'bn') {
    const bnDigits: Record<string, string> = {
      '0': '০',
      '1': '১',
      '2': '২',
      '3': '৩',
      '4': '৪',
      '5': '৫',
      '6': '৬',
      '7': '৭',
      '8': '৮',
      '9': '৯',
    };
    return str.replace(/[0-9]/g, (d) => bnDigits[d] || d);
  }
  return str;
};

